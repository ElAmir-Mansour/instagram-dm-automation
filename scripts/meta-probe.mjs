#!/usr/bin/env node
/**
 * Meta Model API probe: "does api.meta.ai still do what this product relies on?"
 *
 * Every fact about Meta's platform that the code leans on is dated by a probe (constitution V). This is the probe for the Model API behind the
 * Muse provider (src/services/llm/, docs/specs/005-muse-sees). It is a script you run by hand, with the owner's key: NOT part of `npm test` or CI
 * (a test must never spend money or need a key), and nothing imports it but its own test, which touches no network.
 *
 *   node scripts/meta-probe.mjs --env ../.env             the key is META_MODEL_API_KEY in that file (or in the environment)
 *   node scripts/meta-probe.mjs --settings --env ../.env  the key is the one saved in Settings -> AI providers (needs DATABASE_URL and
 *                                                         TOKEN_ENCRYPTION_KEY from the file; read through a read-only connection, and
 *                                                         only when you ask: the database is never opened otherwise)
 *   node scripts/meta-probe.mjs --only text,image         just those
 *   node scripts/meta-probe.mjs --skip image_generation   all but those
 *   node scripts/meta-probe.mjs --video ./clip.mp4        a clip of your own for the video check (otherwise ffmpeg makes one, if it is installed)
 *   node scripts/meta-probe.mjs --json                    machine-readable
 *
 * What it checks, each on its own so one refusal does not end the run (the facts are from the live tests of 2026-10-28 to 10-30):
 *   models            GET /models lists muse-spark-1.3
 *   text              POST /chat/completions with reasoning_effort and a 4,000-token limit answers in text (Muse Spark always reasons, and below about
 *                     1,000 to 2,000 tokens it came back empty)
 *   strict_json       the same, with response_format json_schema strict: true, answers JSON that matches
 *   image             a picture sent as a base64 data URL is read (a generated PNG of the digits 42)
 *   video             a clip sent as a base64 data URL (`video_url`) is watched (generated by ffmpeg, or --video)
 *   asr               POST /asr/transcribe takes a generated 24 kHz mono WAV and answers {transcript, audioDurationMs}
 *   image_generation  POST /images/generations returns an image (b64_json)
 *
 * It prints PASS, FAIL or SKIP with the latency, and for a failure the HTTP status and Meta's error code: never what the model said, never
 * a prompt, never the key. The key is held only to build the Authorization header, and everything printed passes through a redactor that
 * removes it. A real run costs about three cents: five Muse Spark calls of a few thousand tokens ($1.25 in / $4.25 out per million), a few
 * seconds of audio ($0.18 an hour) and one image ($0.01).
 *
 * Exit: 0 nothing failed · 1 at least one check failed · 3 the probe could not run (no key).
 */
